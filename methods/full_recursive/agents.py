# Gemini Client Wrapper
# =============================================================================

class GeminiAgentClient:
    """
    Wrapper for Gemini API calls with grounding support.

    Provides a consistent interface for all agents to call Gemini
    with system prompts and optional Google Search grounding.

    Features:
    - Automatic retry with exponential backoff
    - Cost tracking per call and session
    - Support for Google Search grounding
    """

    # Cost estimates per 1M tokens (rough estimates)
    COST_PER_1M_INPUT = 0.075  # Gemini 2.0 Flash
    COST_PER_1M_OUTPUT = 0.30

    # Retry configuration
    MAX_RETRIES = 3
    INITIAL_BACKOFF_MS = 1000
    MAX_BACKOFF_MS = 30000
    BACKOFF_MULTIPLIER = 2.0

    # Retryable error patterns
    RETRYABLE_ERRORS = [
        "rate limit",
        "quota exceeded",
        "resource exhausted",
        "503",
        "500",
        "timeout",
        "connection",
        "temporarily unavailable",
    ]

    def __init__(
        self,
        api_key: str,
        model: str = "gemini-2.0-flash",
        verbose: bool = False,
        max_retries: int = 3,
    ):
        self.api_key = api_key
        self.model = model
        self.verbose = verbose
        self.max_retries = max_retries
        self._client = None
        self.total_calls = 0
        self.total_retries = 0
        self.total_tokens_input = 0
        self.total_tokens_output = 0
        self.total_cost_usd = 0.0

    def _get_client(self):
        """Lazy-load Gemini client."""
        if self._client is None:
            from google import genai
            self._client = genai.Client(api_key=self.api_key)
        return self._client

    def _is_retryable_error(self, error: Exception) -> bool:
        """Check if an error is retryable."""
        error_str = str(error).lower()
        return any(pattern in error_str for pattern in self.RETRYABLE_ERRORS)

    def _wait_with_backoff(self, attempt: int) -> None:
        """Wait with exponential backoff."""
        backoff_ms = min(
            self.INITIAL_BACKOFF_MS * (self.BACKOFF_MULTIPLIER ** attempt),
            self.MAX_BACKOFF_MS
        )
        # Add jitter (10% randomness)
        import random
        jitter = backoff_ms * 0.1 * random.random()
        wait_time = (backoff_ms + jitter) / 1000.0

        if self.verbose:
            print(f"[Gemini] Retry {attempt + 1}/{self.max_retries}, waiting {wait_time:.1f}s...")

        time.sleep(wait_time)

    def generate(
        self,
        prompt: str,
        system_instruction: str,
        enable_grounding: bool = True,
        temperature: float = 0.7,
    ) -> Tuple[str, Dict[str, Any]]:
        """
        Generate a response from Gemini with automatic retry.

        Args:
            prompt: User prompt
            system_instruction: System prompt for the agent
            enable_grounding: Enable Google Search grounding
            temperature: Temperature for generation

        Returns:
            Tuple of (response_text, metadata_dict)

        Raises:
            Exception: If all retries fail
        """
        from google.genai import types

        client = self._get_client()
        last_error = None

        for attempt in range(self.max_retries + 1):
            try:
                start_time = time.time()

                # Build config
                config = types.GenerateContentConfig(
                    system_instruction=system_instruction,
                    temperature=temperature,
                )

                # Add grounding if enabled
                if enable_grounding:
                    config.tools = [types.Tool(google_search=types.GoogleSearch())]

                # Make the call
                response = client.models.generate_content(
                    model=self.model,
                    contents=prompt,
                    config=config,
                )

                end_time = time.time()
                latency_ms = int((end_time - start_time) * 1000)

                # Extract text
                text = response.text if response.text else ""

                # Try to get token counts from usage metadata
                tokens_input = 0
                tokens_output = 0
                if hasattr(response, 'usage_metadata') and response.usage_metadata:
                    tokens_input = getattr(response.usage_metadata, 'prompt_token_count', 0) or 0
                    tokens_output = getattr(response.usage_metadata, 'candidates_token_count', 0) or 0

                # Update totals
                self.total_calls += 1
                self.total_tokens_input += tokens_input
                self.total_tokens_output += tokens_output

                # Estimate cost
                cost = (tokens_input / 1_000_000 * self.COST_PER_1M_INPUT +
                        tokens_output / 1_000_000 * self.COST_PER_1M_OUTPUT)
                self.total_cost_usd += cost

                metadata = {
                    "latency_ms": latency_ms,
                    "tokens_input": tokens_input,
                    "tokens_output": tokens_output,
                    "cost_estimate_usd": cost,
                    "retries": attempt,
                }

                if self.verbose:
                    retry_info = f" (retry {attempt})" if attempt > 0 else ""
                    print(f"[Gemini] Call {self.total_calls}{retry_info}: {latency_ms}ms, "
                          f"{tokens_input}+{tokens_output} tokens, ${cost:.4f}")

                return text, metadata

            except Exception as e:
                last_error = e
                self.total_retries += 1

                if self.verbose:
                    print(f"[Gemini] Error on attempt {attempt + 1}: {e}")

                # Check if we should retry
                if attempt < self.max_retries and self._is_retryable_error(e):
                    self._wait_with_backoff(attempt)
                else:
                    # Non-retryable error or max retries reached
                    break

        # All retries failed
        raise RuntimeError(f"Gemini API call failed after {self.max_retries + 1} attempts: {last_error}")

    def get_stats(self) -> Dict[str, Any]:
        """Get client usage statistics."""
        return {
            "total_calls": self.total_calls,
            "total_retries": self.total_retries,
            "total_tokens_input": self.total_tokens_input,
            "total_tokens_output": self.total_tokens_output,
            "total_cost_usd": self.total_cost_usd,
            "retry_rate": self.total_retries / max(1, self.total_calls),
        }


