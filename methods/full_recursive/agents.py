def build_synthesizer_prompt(
    market_title: str,
    time_range: Tuple[str, str],
    research_cutoff: str,
    analyst_output: AnalystOutput,
    verifier_output: VerifierOutput,
    iteration: int,
    max_iterations: int,
    confidence_threshold: float,
) -> str:
    """Build the prompt for the synthesizer agent."""
    start, end = time_range

    prompt = f"""SYNTHESIS TASK

Market: {market_title}
Iteration: {iteration} of {max_iterations}
Confidence Threshold: {confidence_threshold}
Market Data Window: {start} to {end}
Research Cutoff: {research_cutoff}

=== ANALYST FINDINGS ===
Overall Confidence: {analyst_output.overall_confidence:.0%}
"""

    for a in analyst_output.answers[:3]:
        prompt += f"- {a.answer[:200]}...\n"

    prompt += f"""
=== VERIFIER ASSESSMENT ===
Adjusted Confidence: {verifier_output.overall_adjusted_confidence:.0%}
Issues Found: {len(verifier_output.issues)}
"""

    for i in verifier_output.issues[:3]:
        prompt += f"- [{i.severity}] {i.description[:100]}...\n"

    if verifier_output.debate_assessment:
        da = verifier_output.debate_assessment
        prompt += f"""
=== DEBATE RESULTS (IMPORTANT) ===
Advocate YES strength: {da.advocate_yes_strength:.0%}
  - Strongest point: {da.advocate_yes_strongest_point[:100]}...
Advocate NO strength: {da.advocate_no_strength:.0%}
  - Strongest point: {da.advocate_no_strongest_point[:100]}...

DEBATE WINNER: {da.winner}
Reasoning: {da.reasoning[:200]}...

NOTE: The debate winner indicates which side had BETTER VERIFIED EVIDENCE.
Weight this heavily in your prediction direction.
"""

    prompt += f"""
=== DECISION REQUIRED ===
- Verifier's adjusted confidence: {verifier_output.overall_adjusted_confidence:.0%}
- Threshold for commit: {confidence_threshold:.0%}
- Iterations remaining: {max_iterations - iteration}

{
    "Confidence meets threshold - you may COMMIT if reasoning is sound."
    if verifier_output.overall_adjusted_confidence >= confidence_threshold
    else "Confidence below threshold - consider RETRY if there are clear gaps to fill, or COMMIT with caveats if no clear improvement path."
}
"""

    if verifier_output.missing_evidence_needs:
        prompt += f"""
Missing evidence identified:
"""
        for e in verifier_output.missing_evidence_needs[:3]:
            prompt += f"- {e}\n"

    prompt += """
Return your synthesis as JSON with prediction, probability, confidence, and decision (COMMIT or RETRY)."""

    return prompt


