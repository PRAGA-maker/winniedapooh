"""
Agent implementations for the full_recursive pipeline.

Each agent:
1. Builds a prompt from input data
2. Calls Gemini API with appropriate system prompt
3. Parses the JSON response
4. Returns structured output + call log

Ported from kalshi-research-agents TypeScript implementation.
"""

