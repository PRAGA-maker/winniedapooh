@dataclass
class SubQuestion:
    """A sub-question generated by the planner."""
    id: str
    question: str
    priority: str = "medium"
    target_date: Optional[str] = None
    reasoning: Optional[str] = None


@dataclass
class PlannerOutput:
    """Output from the planner agent."""
    market_type: Optional[str] = None
    domain_context: Optional[str] = None
    sub_questions: List[SubQuestion] = field(default_factory=list)
    focus_notes: str = ""
    reasoning: str = ""
    confidence: float = 0.5


@dataclass
class Citation:
    """A source citation."""
    url: str
    title: Optional[str] = None
    author: Optional[str] = None
    outlet: Optional[str] = None
    publish_date: Optional[str] = None
    # Wayback validation fields (populated by WaybackValidator)
    wayback_validated: bool = False
    wayback_earliest: Optional[str] = None  # Earliest archive date (YYYY-MM-DD)
    wayback_suspicious: bool = False  # True if no pre-cutoff snapshot found


@dataclass
class AnswerClaim:
    """An answer to a sub-question."""
    question_id: str
    answer: str
    confidence: float = 0.5
    citations: List[Citation] = field(default_factory=list)
    evidence_summary: str = ""
    reasoning: str = ""
    potential_issues: List[str] = field(default_factory=list)


@dataclass
class AnalystOutput:
    """Output from the analyst agent."""
    answers: List[AnswerClaim] = field(default_factory=list)
    all_sources_used: List[Citation] = field(default_factory=list)
    overall_confidence: float = 0.5
    reasoning: str = ""


@dataclass
class AdvocateEvidence:
    """A piece of evidence from an advocate."""
    claim: str
    source: Citation
    strength: float = 0.5
    reasoning: str = ""


@dataclass
class AdvocateOutput:
    """Output from an advocate agent."""
    position: str  # YES or NO
    core_argument: str = ""
    primary_evidence: List[AdvocateEvidence] = field(default_factory=list)
    historical_precedent: str = ""
    anticipated_counterarguments: List[str] = field(default_factory=list)
    rebuttals: List[str] = field(default_factory=list)
    weakest_point: str = ""
    confidence: float = 0.5
    reasoning: str = ""
    all_sources_used: List[Citation] = field(default_factory=list)


@dataclass
class Issue:
    """An issue identified by the verifier."""
    type: str  # leakage, coverage, logic, bias, gap, contradiction
    severity: str  # critical, major, minor
    description: str
    affected_claims: List[str] = field(default_factory=list)
    recommendation: Optional[str] = None


@dataclass
class DebateAssessment:
    """Assessment of the advocate debate."""
    advocate_yes_strength: float = 0.5
    advocate_yes_strongest_point: str = ""
    advocate_yes_weakest_point: str = ""
    advocate_no_strength: float = 0.5
    advocate_no_strongest_point: str = ""
    advocate_no_weakest_point: str = ""
    winner: str = "TIE"  # YES, NO, or TIE
    reasoning: str = ""


@dataclass
class VerifierOutput:
    """Output from the verifier agent."""
    issues: List[Issue] = field(default_factory=list)
    debate_assessment: Optional[DebateAssessment] = None
    adjusted_confidences: Dict[str, float] = field(default_factory=dict)
    overall_adjusted_confidence: float = 0.5
    missing_evidence_needs: List[str] = field(default_factory=list)
    reasoning: str = ""


@dataclass
class KeyEvidence:
    """Key evidence supporting a prediction."""
    claim: str
    source: str
    weight: float = 0.5


@dataclass
class SynthesizerOutput:
    """Output from the synthesizer agent."""
    prediction: str = ""
    probability: float = 0.5
    confidence: float = 0.5
    decision: str = "COMMIT"  # COMMIT or RETRY
    reasoning: str = ""
    key_evidence: List[KeyEvidence] = field(default_factory=list)
    caveats: List[str] = field(default_factory=list)
    retry_focus: Optional[List[str]] = None


@dataclass
class LLMCallLog:
    """Log of an LLM API call."""
    call_id: str
    agent: str
    timestamp: str
    iteration: int
    latency_ms: int
    tokens_input: int = 0
    tokens_output: int = 0
    cost_estimate_usd: float = 0.0
    raw_response: str = ""
    parse_error: Optional[str] = None


