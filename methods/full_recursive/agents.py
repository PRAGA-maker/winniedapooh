def parse_advocate_response(text: str, position: str) -> Optional[AdvocateOutput]:
    """Parse advocate agent response."""
    parsed = extract_json(text)
    if not parsed:
        return None

    try:
        primary_evidence = []
        for e in safe_get(parsed, "primaryEvidence", "primary_evidence", default=[]):
            source_data = safe_get(e, "source", default={})
            source = Citation(
                url=safe_get(source_data, "url", default=safe_get(e, "url", default="")),
                title=safe_get(source_data, "title", default=safe_get(e, "title")),
                author=safe_get(source_data, "author"),
                outlet=safe_get(source_data, "outlet"),
                publish_date=safe_get(source_data, "publishDate", "publish_date"),
            )
            primary_evidence.append(AdvocateEvidence(
                claim=safe_get(e, "claim", default=""),
                source=source,
                strength=safe_get(e, "strength", default=0.5),
                reasoning=safe_get(e, "reasoning", default=""),
            ))

        all_sources = []
        for s in safe_get(parsed, "allSourcesUsed", "all_sources_used", default=[]):
            all_sources.append(Citation(
                url=safe_get(s, "url", default=""),
                title=safe_get(s, "title"),
            ))

        # Also add sources from evidence if allSourcesUsed is empty
        if not all_sources:
            seen_urls = set()
            for e in primary_evidence:
                if e.source.url and e.source.url not in seen_urls:
                    seen_urls.add(e.source.url)
                    all_sources.append(e.source)

        return AdvocateOutput(
            position=safe_get(parsed, "position", default=position),
            core_argument=safe_get(parsed, "coreArgument", "core_argument", default=""),
            primary_evidence=primary_evidence,
            historical_precedent=safe_get(parsed, "historicalPrecedent", "historical_precedent", default=""),
            anticipated_counterarguments=safe_get(parsed, "anticipatedCounterarguments", "anticipated_counterarguments", default=[]),
            rebuttals=safe_get(parsed, "rebuttals", default=[]),
            weakest_point=safe_get(parsed, "weakestPoint", "weakest_point", default=""),
            confidence=safe_get(parsed, "confidence", default=0.5),
            reasoning=safe_get(parsed, "reasoning", default=""),
            all_sources_used=all_sources,
        )
    except Exception:
        return None


