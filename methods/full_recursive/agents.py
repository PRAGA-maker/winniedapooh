def build_analyst_prompt(
    market_title: str,
    sub_questions: List[SubQuestion],
    time_range: Tuple[str, str],
    research_cutoff: str,
    seen_urls: Optional[Set[str]] = None,
) -> str:
    """Build the prompt for the analyst agent."""
    start, end = time_range

    prompt = f"""RESEARCH TASK

Market: {market_title}
Market Data Window: {start} to {end}

RESEARCH CUTOFF DATE: {research_cutoff}
CRITICAL CONSTRAINT: Only use sources published BEFORE {research_cutoff}.

SUB-QUESTIONS TO RESEARCH:
"""

    for i, q in enumerate(sub_questions):
        prompt += f"{i+1}. [{q.id}] {q.question}\n"
        prompt += f"   Priority: {q.priority}\n"
        if q.target_date:
            prompt += f"   Target date: {q.target_date}\n"
        prompt += "\n"

    # Add previously cited sources to avoid re-citing them
    if seen_urls and len(seen_urls) > 0:
        prompt += """
ALREADY CITED SOURCES (do NOT re-cite these - find NEW sources instead):
"""
        # Limit to 20 URLs to avoid prompt bloat
        for url in list(seen_urls)[:20]:
            prompt += f"- {url}\n"
        if len(seen_urls) > 20:
            prompt += f"... and {len(seen_urls) - 20} more\n"
        prompt += "\n"

    prompt += """
For each question:
1. Search for relevant evidence
2. Verify source dates are before cutoff
3. Score source credibility
4. Synthesize findings with confidence

Return your analysis as JSON."""

    return prompt


def parse_analyst_response(text: str) -> Optional[AnalystOutput]:
    """Parse analyst agent response."""
    parsed = extract_json(text)
    if not parsed:
        return None

    try:
        answers = []
        raw_answers = safe_get(parsed, "answers", default=[])
        for a in raw_answers:
            citations = []
            for c in safe_get(a, "citations", default=[]):
                citations.append(Citation(
                    url=safe_get(c, "url", default=""),
                    title=safe_get(c, "title"),
                    author=safe_get(c, "author"),
                    outlet=safe_get(c, "outlet"),
                    publish_date=safe_get(c, "publishDate", "publish_date"),
                ))

            answers.append(AnswerClaim(
                question_id=safe_get(a, "questionId", "question_id", default=""),
                answer=safe_get(a, "answer", default=""),
                confidence=safe_get(a, "confidence", default=0.5),
                citations=citations,
                evidence_summary=safe_get(a, "evidenceSummary", "evidence_summary", default=""),
                reasoning=safe_get(a, "reasoning", default=""),
                potential_issues=safe_get(a, "potentialIssues", "potential_issues", default=[]),
            ))

        all_sources = []
        for s in safe_get(parsed, "allSourcesUsed", "all_sources_used", default=[]):
            all_sources.append(Citation(
                url=safe_get(s, "url", default=""),
                title=safe_get(s, "title"),
            ))

        return AnalystOutput(
            answers=answers,
            all_sources_used=all_sources,
            overall_confidence=safe_get(parsed, "overallConfidence", "overall_confidence", default=0.5),
            reasoning=safe_get(parsed, "reasoning", default=""),
        )
    except Exception:
        return None


